#!/usr/bin/env bash
# Reproduce the v0.2.0 results in three tiers.
#
#   scripts/reproduce.sh fast       fast tests, README tables and figures from committed data
#   scripts/reproduce.sh analysis   every analysis script, in a throwaway clone of HEAD
#   scripts/reproduce.sh collect    print (do not run) every sampling command
#
# fast and analysis never modify this work tree. Figures and results are written to a
# temporary directory and compared with the committed files: results/*.json field by
# field, ignoring git_describe; figures byte for byte. PNG bytes depend on the
# matplotlib and FreeType build, so a figure difference is reported but does not fail
# the run (docs/METHODS.md#reproducibility). Bootstrap CI endpoints depend on the
# NumPy build (docs/METHODS.md#numpy-dependent-ci-endpoints).
#
# analysis runs HEAD only: uncommitted changes are not included. Each analysis script
# refuses a dirty work tree, so the clone commits each script's output before the next.
# analysis tier: 7 min 14 s wall time (7 min 0 s user CPU), one run on an Apple M2 under
# caffeinate -i, including uv start-up (source: the message of commit `17edff9`).
#
# collect prints the commands that sample new shots: the sweeps behind data/*.csv and
# data/wu/*.csv, and the ablation. Collection appends to the committed CSVs; only the
# maintainer runs it. Wall times are given where a run was recorded.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

usage() {
    sed -n '2,6p' "$0" | sed 's/^# \{0,1\}//'
    exit 2
}

make_tmp() {
    TMP="$(mktemp -d "${TMPDIR:-/tmp}/erasure-qec-reproduce.XXXXXX")"
    trap 'rm -rf "$TMP"' EXIT
}

# compare_json COMMITTED REGENERATED: exit 0 if equal ignoring git_describe.
compare_json() {
    uv run python - "$1" "$2" <<'EOF'
import json
import sys

def load(path):
    doc = json.load(open(path))
    doc.pop("git_describe", None)
    return doc

def first_diff(a, b, path="$"):
    if type(a) is not type(b):
        return path
    if isinstance(a, dict):
        for key in sorted(set(a) | set(b)):
            if key not in a or key not in b:
                return f"{path}.{key}"
            found = first_diff(a[key], b[key], f"{path}.{key}")
            if found:
                return found
        return None
    if isinstance(a, list):
        if len(a) != len(b):
            return f"{path} (length)"
        for i, (x, y) in enumerate(zip(a, b)):
            found = first_diff(x, y, f"{path}[{i}]")
            if found:
                return found
        return None
    return None if a == b else path

where = first_diff(load(sys.argv[1]), load(sys.argv[2]))
if where:
    print(f"  DIFFERS  {sys.argv[1]} (first difference at {where})")
    sys.exit(1)
print(f"  MATCH    {sys.argv[1]}")
EOF
}

# compare_figures REGENERATED_DIR NAME...: report byte identity; never fails.
compare_figures() {
    local dir="$1"
    shift
    for name in "$@"; do
        if cmp -s "$dir/$name" "$ROOT/figures/$name"; then
            echo "  MATCH    figures/$name"
        else
            echo "  DIFFERS  figures/$name (PNG bytes are environment dependent)"
        fi
    done
}

fast() {
    make_tmp
    echo "== fast tests (includes the README table sync and circuit golden tests)"
    uv run pytest -m "not slow" -q
    echo "== README tables from results/*.json"
    uv run python scripts/render_readme_tables.py >/dev/null
    echo "  rendered; equality with README.md is asserted by"
    echo "  tests/test_readme_tables_in_sync.py above"
    echo "== figures from data/*.csv and results/ablation.json"
    uv run python -m erasure_qec.analysis.plotting --data-dir data \
        --figures-dir "$TMP/figures" --ablation-json results/ablation.json >/dev/null
    compare_figures "$TMP/figures" threshold_panels.png lambda_vs_p.png ablation.png \
        hook_regression.png
    echo "fast: done (figures/wu_validation.png is regenerated by the analysis tier)"
}

analysis() {
    make_tmp
    if [ -n "$(git status --porcelain)" ]; then
        echo "note: the work tree has uncommitted changes; analysis runs HEAD without them"
    fi
    local clone="$TMP/clone"
    git clone --quiet --shared "$ROOT" "$clone"
    git -C "$clone" checkout --quiet --detach "$(git rev-parse HEAD)"

    step() {
        local name="$1"
        shift
        echo "== $name"
        (cd "$clone" && "$@")
        git -C "$clone" add -A results figures
        git -C "$clone" -c user.name=reproduce -c user.email=reproduce@localhost \
            commit --quiet --allow-empty -m "reproduce: $name"
    }

    step "pairwise crossings and fits, both metrics" \
        uv run python scripts/threshold_table.py --out results/threshold_table_dense.json
    step "headline thresholds and herald - blind" uv run python scripts/headline_results.py
    step "per-round fit sensitivity" uv run python scripts/per_round_fit_sensitivity.py
    step "Wu G5 check" uv run python scripts/wu_g5_check.py
    step "Wu validation table, JSON and figure" uv run python scripts/wu_validation.py
    echo "== heralded fraction"
    (cd "$clone" && uv run python scripts/heralded_fraction.py)
    echo "  compare with docs/archive/remediation/baseline_outputs/heralded_fraction.txt"

    echo "== comparison with the committed results"
    local failed=0
    for name in threshold_table_dense.json headline.json per_round_fit_sensitivity.json \
        wu_validation.json; do
        compare_json "results/$name" "$clone/results/$name" || failed=1
    done
    compare_figures "$clone/figures" wu_validation.png
    echo "not re-run: results/ablation.json (sampling; see the collect tier) and"
    echo "results/threshold_table_committed.json (pre-dense sweeps, superseded)"
    if [ "$failed" -ne 0 ]; then
        echo "analysis: some results differ from the committed files" >&2
        exit 1
    fi
    echo "analysis: done"
}

collect() {
    cat <<'EOF'
