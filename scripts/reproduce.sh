Repo-convention sweeps (data/*.csv). Wall time: not timed.
  nohup uv run python experiments/collect_threshold_sweep.py experiments/configs/baseline_pauli.yaml --workers 8 > logs/collect_baseline_pauli.log 2>&1 &
